fn draw_board_overlay(
    frame: &mut Frame,
    photo_assets: &PhotoBoardAssets,
    compact_crop: bool,
    keys: &[Key],
    highlighted: &HashMap<KeyId, usize>,
    overlay_highlighted: Option<&HashMap<KeyId, usize>>,
    play_order: Option<&HashMap<KeyId, Vec<usize>>>,
    selected_controls: &HashSet<KeyId>,
    pressed: &HashSet<KeyId>,
    projected_labels: Option<&HashMap<KeyId, String>>,
    drum_note_to_key: &HashMap<u8, KeyId>,
    show_drum_symbols: bool,
    knob_values: &[f32],
    active_knob: Option<(u8, f32)>,
    badges: &mut Vec<(Rectangle, Vec<usize>)>,
    knob_pointers: &mut Vec<(Rectangle, f32)>,
) {
    let size = frame.size();
    let display_bezel_rect = photo_rect(size, compact_crop, 1282.0, 187.0, 233.0, 90.0);
    let display_text = active_knob
        .and_then(|(idx, value)| knob_readout(idx, value))
        .unwrap_or_else(|| "MIDI READY".to_string());
    frame.fill_text(Text {
        content: display_text,
        position: Point::new(
            display_bezel_rect.x + display_bezel_rect.width / 2.0,
            display_bezel_rect.y + display_bezel_rect.height / 2.0,
        ),
        // Same amber as the header LCD's own readout text (`LCD_TEXT` in
        // main.rs) — one on-board display, one off-board, same material.
        color: rgb(0xE9, 0x9B, 0x24),
        size: iced::Pixels(
            (board_rect(size, compact_crop).width / PHOTO_WIDTH * 14.0).clamp(7.0, 14.0),
        ),
        font: CANVAS_FONT,
        align_x: Horizontal::Center.into(),
        align_y: Vertical::Center,
        ..Text::default()
    });

    draw_tape_labels(frame, size, compact_crop);

    for key in keys {
        let rect = key_rect_with_size(key, size, compact_crop);
        let lit_track = overlay_highlighted
            .and_then(|overlay| overlay.get(&key.id))
            .copied()
            .or_else(|| highlighted.get(&key.id).copied())
            .or_else(|| {
                (selected_controls.contains(&key.id) || pressed.contains(&key.id))
                    .then_some(usize::MAX)
            });

        if key.is_knob {
            let value = key
                .knob_index
                .and_then(|idx| knob_values.get(idx as usize))
                .copied()
                .unwrap_or(0.0);
            let label = key
                .knob_index
                .and_then(|idx| crate::synth::KNOB_PARAMS.get(idx as usize))
                .map(|param| param.label);
            draw_knob(frame, rect, label, &photo_assets.knob_face);
            knob_pointers.push((rect, value));
            continue;
        }

        let (_, text_color) = key_colors(key.cluster, lit_track);
        let press_offset = lit_track
            .map(|_| (rect.height * 0.055).clamp(1.0, 4.0))
            .unwrap_or(0.0);
        let mut sprite_rect = key_sprite_rect_with_size(key, size, compact_crop, show_drum_symbols);
        sprite_rect.y += press_offset;
        if let Some(sprite) = photo_assets.key_sprite(key, lit_track, show_drum_symbols) {
            frame.draw_image(sprite_rect, &sprite);
        }
        let visual_rect = Rectangle {
            y: rect.y + press_offset,
            ..rect
        };

        let drum_note = show_drum_symbols
            .then(|| {
                drum_note_to_key
                    .iter()
                    .find_map(|(&note, &id)| (id == key.id).then_some(note))
            })
            .flatten();
        let projected_label = projected_labels.and_then(|labels| labels.get(&key.id));

        if let Some(note) = drum_note {
            let label_rect = if matches!(key.cluster, Cluster::Numpad) {
                if let Some(mut bounds) = numpad_text_bounds_with_size(key, size, compact_crop) {
                    bounds.y += press_offset;
                    bounds
                } else {
                    visual_rect
                }
            } else {
                visual_rect
            };
            draw_drum_symbol(
                frame,
                label_rect,
                note,
                text_color,
                projected_label.map(String::as_str),
            );
            if let Some(steps) = play_order.and_then(|order| order.get(&key.id)) {
                badges.push((visual_rect, steps.clone()));
            }
            continue;
        }

        let (primary_label, secondary_label) = match key.cluster {
            Cluster::Alpha | Cluster::AlphaLight => (
                projected_label.map(String::as_str).unwrap_or(key.label),
                if projected_label.is_some() {
                    Some(key.label)
                } else {
                    None
                },
            ),
            Cluster::Nav | Cluster::Arrow => {
                (projected_label.map(String::as_str).unwrap_or(""), None)
            }
            // The numpad's computer-key labels only ever add information as
            // the small corner hint drawn by `draw_drum_symbol` above, once
            // drum symbols replace its photographed digits. Outside that
            // mode the real photographed numpad already shows the same
            // digit, so drawing it again here would just double it.
            Cluster::Numpad => ("", None),
            Cluster::Encoder => unreachable!(),
        };

        let board_scale = board_rect(size, compact_crop).width / PHOTO_WIDTH;
        let (label_anchor, label_bounds) =
            if matches!(key.cluster, Cluster::Alpha | Cluster::AlphaLight) {
                if let Some((mut anchor, mut bounds)) =
                    alpha_text_guide_with_size(key, size, compact_crop)
                {
                    anchor.y += press_offset;
                    if let Some(region) = bounds.as_mut() {
                        region.y += press_offset;
                    }
                    (anchor, bounds)
                } else {
                    (
                        Point::new(
                            visual_rect.x + visual_rect.width / 2.0,
                            visual_rect.y + visual_rect.height / 2.0,
                        ),
                        None,
                    )
                }
            } else {
                (
                    Point::new(
                        visual_rect.x + visual_rect.width / 2.0,
                        visual_rect.y + visual_rect.height / 2.0,
                    ),
                    None,
                )
            };

        if !primary_label.is_empty() {
            fill_text_with_bounds(
                frame,
                Text {
                    content: primary_label.to_string(),
                    position: Point::new(
                        label_anchor.x,
                        label_anchor.y
                            - if secondary_label.is_some() {
                                6.0 * board_scale
                            } else {
                                0.0
                            },
                    ),
                    color: text_color,
                    size: iced::Pixels(
                        ((if primary_label.len() > 4 { 11.0 } else { 14.0 }) * board_scale)
                            .clamp(5.0, 14.0),
                    ),
                    font: CANVAS_FONT,
                    align_x: Horizontal::Center.into(),
                    align_y: Vertical::Center,
                    ..Text::default()
                },
                label_bounds,
            );
        }

        if let Some(sub) = secondary_label {
            fill_text_with_bounds(
                frame,
                Text {
                    content: sub.to_string(),
                    position: Point::new(label_anchor.x, label_anchor.y + 12.0 * board_scale),
                    color: Color::from_rgba8(0, 0, 0, 0.6),
                    size: iced::Pixels((10.0 * board_scale).clamp(4.0, 10.0)),
                    font: CANVAS_FONT,
                    align_x: Horizontal::Center.into(),
                    align_y: Vertical::Center,
                    ..Text::default()
                },
                label_bounds,
            );
        }

        if let Some(steps) = play_order.and_then(|order| order.get(&key.id)) {
            badges.push((visual_rect, steps.clone()));
        }
    }
}

