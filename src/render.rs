pub struct BoardCanvas<'a> {
    pub photo_assets: &'a PhotoBoardAssets,
    /// Keep the board at its width-derived scale and let the canvas clip the
    /// excess top/bottom instead of shrinking the whole instrument.
    pub compact_crop: bool,
    pub keys: &'a [Key],
    /// Maps KeyId → track index for color. usize::MAX = manually toggled (uses original colour).
    pub highlighted: &'a HashMap<KeyId, usize>,
    /// Optional live overlay (for browser MIDI input) drawn above the base
    /// playback/selection highlight without requiring a temporary merged map.
    pub overlay_highlighted: Option<&'a HashMap<KeyId, usize>>,
    /// Chronological play steps to badge onto highlighted keys while a staff
    /// range is selected. Chords share a number; repeated keys have several.
    pub play_order: Option<&'a HashMap<KeyId, Vec<usize>>>,
    /// Persistently-active control keys (e.g. layered waveform selects),
    /// independent of playback note overlays.
    pub selected_controls: &'a HashSet<KeyId>,
    /// Keys currently held with the pointer.
    pub pressed: &'a HashSet<KeyId>,
    /// Computer-key labels shown over the note names in performance mode.
    pub projected_labels: Option<&'a HashMap<KeyId, String>>,
    /// GM drum assignments for the numpad's 4x5 pad grid.
    pub drum_note_to_key: &'a HashMap<u8, KeyId>,
    /// Replace the numpad legends with instrument icons and names.
    pub show_drum_symbols: bool,
    /// Current 0.0..=1.0 dial position of each of the 12 encoder knobs.
    pub knob_values: &'a [f32],
}

/// The narrow grab rail attached to the bottom edge of the photographic board.
/// It owns the pointer drag state so resizing never enters the keyboard's much
/// busier note/knob event path.
pub struct BoardResizeHandle {
    pub current_height: f32,
    pub min_height: f32,
    pub max_height: f32,
}

#[derive(Debug, Clone, Copy)]
enum ResizePointer {
    Mouse,
    Touch(touch::Finger),
}

#[derive(Debug, Clone, Copy)]
struct ResizeDrag {
    pointer: ResizePointer,
    start_y: f32,
    start_height: f32,
}

#[derive(Default)]
pub struct BoardResizeState {
    drag: Option<ResizeDrag>,
}

fn resized_keyboard_height(start: f32, delta_y: f32, min: f32, max: f32) -> f32 {
    (start + delta_y).clamp(min.min(max), max.max(min))
}

impl canvas::Program<Message> for BoardResizeHandle {
    type State = BoardResizeState;

    fn update(
        &self,
        state: &mut Self::State,
        event: &canvas::Event,
        bounds: Rectangle,
        cursor: mouse::Cursor,
    ) -> Option<canvas::Action<Message>> {
        match event {
            canvas::Event::Mouse(mouse::Event::ButtonPressed(mouse::Button::Left)) => {
                let position = cursor.position()?;
                if bounds.contains(position) {
                    state.drag = Some(ResizeDrag {
                        pointer: ResizePointer::Mouse,
                        start_y: position.y,
                        start_height: self.current_height,
                    });
                    return Some(canvas::Action::capture());
                }
            }
            canvas::Event::Mouse(mouse::Event::CursorMoved { .. }) => {
                if let Some(ResizeDrag {
                    pointer: ResizePointer::Mouse,
                    start_y,
                    start_height,
                }) = state.drag
                {
                    if let Some(position) = cursor.position() {
                        let height = resized_keyboard_height(
                            start_height,
                            position.y - start_y,
                            self.min_height,
                            self.max_height,
                        );
                        return Some(
                            canvas::Action::publish(Message::KeyboardHeightChanged(height))
                                .and_capture(),
                        );
                    }
                }
            }
            canvas::Event::Mouse(mouse::Event::ButtonReleased(mouse::Button::Left)) => {
                if matches!(
                    state.drag.map(|drag| drag.pointer),
                    Some(ResizePointer::Mouse)
                ) {
                    state.drag = None;
                    return Some(canvas::Action::capture());
                }
            }
            canvas::Event::Touch(touch::Event::FingerPressed { id, position }) => {
                if state.drag.is_none() && bounds.contains(*position) {
                    state.drag = Some(ResizeDrag {
                        pointer: ResizePointer::Touch(*id),
                        start_y: position.y,
                        start_height: self.current_height,
                    });
                    return Some(canvas::Action::capture());
                }
            }
            canvas::Event::Touch(touch::Event::FingerMoved { id, position }) => {
                if let Some(ResizeDrag {
                    pointer: ResizePointer::Touch(active_id),
                    start_y,
                    start_height,
                }) = state.drag
                {
                    if *id == active_id {
                        let height = resized_keyboard_height(
                            start_height,
                            position.y - start_y,
                            self.min_height,
                            self.max_height,
                        );
                        return Some(
                            canvas::Action::publish(Message::KeyboardHeightChanged(height))
                                .and_capture(),
                        );
                    }
                }
            }
            canvas::Event::Touch(touch::Event::FingerLifted { id, .. })
            | canvas::Event::Touch(touch::Event::FingerLost { id, .. }) => {
                if matches!(
                    state.drag.map(|drag| drag.pointer),
                    Some(ResizePointer::Touch(active_id)) if active_id == *id
                ) {
                    state.drag = None;
                    return Some(canvas::Action::capture());
                }
            }
            _ => {}
        }

        None
    }

    fn draw(
        &self,
        state: &Self::State,
        renderer: &Renderer,
        _theme: &Theme,
        bounds: Rectangle,
        _cursor: mouse::Cursor,
    ) -> Vec<Geometry> {
        let mut frame = Frame::new(renderer, bounds.size());
        let width = frame.width();
        let height = frame.height();
        let active = state.drag.is_some();

        frame.fill(
            &Path::rectangle(Point::ORIGIN, frame.size()),
            rgb(0x11, 0x12, 0x0F),
        );
        frame.fill(
            &Path::rectangle(Point::new(0.0, 0.0), Size::new(width, 1.0)),
            rgb(0x3A, 0x39, 0x2E),
        );

        let grip_width = (width * 0.16).clamp(72.0, 220.0);
        let grip_x = (width - grip_width) / 2.0;
        let grip_color = if active {
            rgb(0xE9, 0x9B, 0x24)
        } else {
            rgb(0x91, 0x8C, 0x7D)
        };
        for offset in [-2.5, 2.5] {
            frame.fill(
                &rounded_rect(
                    Rectangle {
                        x: grip_x,
                        y: height / 2.0 + offset - 1.0,
                        width: grip_width,
                        height: 2.0,
                    },
                    1.0,
                ),
                grip_color,
            );
        }

        vec![frame.into_geometry()]
    }

    fn mouse_interaction(
        &self,
        state: &Self::State,
        bounds: Rectangle,
        cursor: mouse::Cursor,
    ) -> mouse::Interaction {
        if state.drag.is_some() || cursor.is_over(bounds) {
            mouse::Interaction::ResizingVertically
        } else {
            mouse::Interaction::default()
        }
    }
}

#[derive(Default)]
pub struct CanvasState {
    photo_cache: canvas::Cache,
    photo_crop_cache: canvas::Cache,
    overlay_cache: canvas::Cache,
    /// The knob drag popup gets its own geometry layer, separate from the
    /// crowded overlay frame — some large fills/thick strokes silently fail
    /// to render when they land late in a frame packed with hundreds of
    /// other draw calls (also seen on the numpad's drum-pad icons), and an
    /// isolated frame with far fewer prior draws reliably avoids it.
    slider_cache: canvas::Cache,
    /// Play-order badges get the same isolated-layer treatment as the knob
    /// slider popup — see `slider_cache`.
    badge_cache: canvas::Cache,
    /// The knob pointers (thin strokes, landing late in the same
    /// hundreds-of-draw-calls overlay frame as every key and the 13 knob
    /// face images) get the same isolated-layer treatment as `slider_cache`
    /// — otherwise they silently fail to render at all.
    knob_pointer_cache: canvas::Cache,
    pressed: Option<KeyId>,
    dragging_knob: Option<u8>,
    /// (cursor Y, knob value) captured on mouse-down, so dragging moves the
    /// value relative to where it already was instead of snapping it to
    /// whatever absolute position the click happened to land on — the knob
    /// itself sits above the pop-up track, so an absolute mapping always
    /// started the drag off the top or bottom of the track.
    drag_start: Option<(f32, f32)>,
}

/// Vertical extent of the pop-up slider shown while a knob is held, in
/// canvas-local coordinates. Cursor movement is mapped onto this range as a
/// delta from the drag's starting point (see `drag_start`), over a much
/// longer travel than the knob itself — far easier to land on a precise
/// setting than eyeballing rotation on a small dial.
fn knob_slider_track(knob_rect: Rectangle) -> (f32, f32) {
    let top = knob_rect.y + knob_rect.height + 22.0;
    (top, top + 160.0)
}

impl<'a> canvas::Program<Message> for BoardCanvas<'a> {
    type State = CanvasState;

    fn update(
        &self,
        state: &mut Self::State,
        event: &canvas::Event,
        bounds: Rectangle,
        cursor: mouse::Cursor,
    ) -> Option<canvas::Action<Message>> {
        match event {
            canvas::Event::Mouse(mouse::Event::ButtonPressed(mouse::Button::Left)) => {
                if let Some(pos) = cursor.position_in(bounds) {
                    for key in self.keys {
                        if key_rect_with_size(key, bounds.size(), self.compact_crop).contains(pos) {
                            if let Some(idx) = key.knob_index {
                                state.dragging_knob = Some(idx);
                                let current =
                                    self.knob_values.get(idx as usize).copied().unwrap_or(0.0);
                                // Anchor on the cursor's absolute (window) position, not the
                                // canvas-local one — `CursorMoved` below needs to keep tracking
                                // the drag even once the pointer leaves the canvas bounds
                                // (e.g. dragging a top-row knob upward past the board edge).
                                let start_y = cursor.position().map(|p| p.y).unwrap_or(pos.y);
                                state.drag_start = Some((start_y, current));
                                return Some(canvas::Action::capture());
                            }
                            state.pressed = Some(key.id);
                            return Some(
                                canvas::Action::publish(Message::KeyPressed(key.id)).and_capture(),
                            );
                        }
                    }
                }
            }
            canvas::Event::Mouse(mouse::Event::CursorMoved { .. }) => {
                if let Some(idx) = state.dragging_knob {
                    // Use the cursor's absolute position rather than
                    // `position_in(bounds)` — once the drag starts, the
                    // pointer is free to move outside the canvas (e.g.
                    // above a top-row knob) and should keep being tracked.
                    if let Some(pos) = cursor.position() {
                        if let Some(knob_rect) = self
                            .keys
                            .iter()
                            .find(|key| key.knob_index == Some(idx))
                            .map(|key| key_rect_with_size(key, bounds.size(), self.compact_crop))
                        {
                            let (top, bottom) = knob_slider_track(knob_rect);
                            let (start_y, start_value) = state.drag_start.unwrap_or((pos.y, 0.0));
                            let delta = (pos.y - start_y) / (bottom - top);
                            let value = (start_value - delta).clamp(0.0, 1.0);
                            return Some(
                                canvas::Action::publish(Message::KnobChanged(idx, value))
                                    .and_capture(),
                            );
                        }
                    }
                }
            }
            canvas::Event::Mouse(mouse::Event::ButtonReleased(mouse::Button::Left)) => {
                state.drag_start = None;
                if state.dragging_knob.take().is_some() {
                    return Some(canvas::Action::capture());
                }
                if let Some(id) = state.pressed.take() {
                    return Some(canvas::Action::publish(Message::KeyReleased(id)).and_capture());
                }
            }
            // Hovering a knob and scrolling nudges its value — much easier
            // than dragging to "turn" it, which is what click-drag simulates.
            canvas::Event::Mouse(mouse::Event::WheelScrolled { delta }) => {
                if let Some(pos) = cursor.position_in(bounds) {
                    for key in self.keys {
                        if key_rect_with_size(key, bounds.size(), self.compact_crop).contains(pos) {
                            if let Some(idx) = key.knob_index {
                                let amount = match *delta {
                                    mouse::ScrollDelta::Lines { y, .. } => y * 0.05,
                                    mouse::ScrollDelta::Pixels { y, .. } => y / 200.0,
                                };
                                let current =
                                    self.knob_values.get(idx as usize).copied().unwrap_or(0.0);
                                let value = (current + amount).clamp(0.0, 1.0);
                                return Some(
                                    canvas::Action::publish(Message::KnobChanged(idx, value))
                                        .and_capture(),
                                );
                            }
                            break;
                        }
                    }
                }
            }
            _ => {}
        }
        None
    }

    fn draw(
        &self,
        state: &Self::State,
        renderer: &Renderer,
        _theme: &Theme,
        bounds: Rectangle,
        _cursor: mouse::Cursor,
    ) -> Vec<Geometry> {
        state.overlay_cache.clear(); // highlights can change every 16 ms during playback
        state.knob_pointer_cache.clear(); // knob values can change just as often
        let active_knob = state.dragging_knob.map(|idx| {
            (
                idx,
                self.knob_values.get(idx as usize).copied().unwrap_or(0.0),
            )
        });
        let photo_cache = if self.compact_crop {
            &state.photo_crop_cache
        } else {
            &state.photo_cache
        };
        let photo_geometry = photo_cache.draw(renderer, bounds.size(), |frame| {
            frame.with_clip(canvas_clip(bounds.size()), |frame| {
                draw_board_base(frame, self.photo_assets, self.compact_crop);
            });
        });
        let mut badges: Vec<(Rectangle, Vec<usize>)> = Vec::new();
        let mut knob_pointers: Vec<(Rectangle, f32)> = Vec::new();
        let overlay_geometry = state.overlay_cache.draw(renderer, bounds.size(), |frame| {
            frame.with_clip(canvas_clip(bounds.size()), |frame| {
                draw_board_overlay(
                    frame,
                    self.photo_assets,
                    self.compact_crop,
                    self.keys,
                    self.highlighted,
                    self.overlay_highlighted,
                    self.play_order,
                    self.selected_controls,
                    self.pressed,
                    self.projected_labels,
                    self.drum_note_to_key,
                    self.show_drum_symbols,
                    self.knob_values,
                    active_knob,
                    &mut badges,
                    &mut knob_pointers,
                );
            });
        });
        // Keep interaction imagery separate from the cached photographic base
        // so active, colour-swapped key sprites render above the resting rows.
        let mut geometries = vec![photo_geometry, overlay_geometry];

        // The knob pointers are their own isolated geometry — see
        // `knob_pointer_cache`'s doc comment for why they can't just be the
        // last thing drawn into the (already large) overlay frame.
        if !knob_pointers.is_empty() {
            let pointer_geometry =
                state
                    .knob_pointer_cache
                    .draw(renderer, bounds.size(), |frame| {
                        frame.with_clip(canvas_clip(bounds.size()), |frame| {
                            for (rect, value) in &knob_pointers {
                                draw_knob_pointer(frame, *rect, *value);
                            }
                        });
                    });
            geometries.push(pointer_geometry);
        }

        // The knob drag popup is its own isolated geometry — see the
        // `slider_cache` doc comment for why it can't just be the last thing
        // drawn into the (already large) overlay frame.
        if let Some((idx, value)) = active_knob {
            state.slider_cache.clear();
            let slider_geometry = state.slider_cache.draw(renderer, bounds.size(), |frame| {
                if let Some(knob_rect) = self
                    .keys
                    .iter()
                    .find(|key| key.knob_index == Some(idx))
                    .map(|key| key_rect_with_size(key, bounds.size(), self.compact_crop))
                {
                    draw_knob_slider(frame, knob_rect, value, knob_readout(idx, value));
                }
            });
            geometries.push(slider_geometry);
        }

        // Play-order badges also get their own isolated geometry — see the
        // `badge_cache` doc comment.
        if !badges.is_empty() {
            state.badge_cache.clear();
            let badge_geometry = state.badge_cache.draw(renderer, bounds.size(), |frame| {
                for (rect, steps) in &badges {
                    draw_play_order_badge(frame, *rect, steps);
                }
            });
            geometries.push(badge_geometry);
        }

        geometries
    }

    fn mouse_interaction(
        &self,
        state: &Self::State,
        bounds: Rectangle,
        cursor: mouse::Cursor,
    ) -> mouse::Interaction {
        if state.dragging_knob.is_some() {
            return mouse::Interaction::ResizingVertically;
        }
        if let Some(pos) = cursor.position_in(bounds) {
            for key in self.keys {
                if key_rect_with_size(key, bounds.size(), self.compact_crop).contains(pos) {
                    if key.is_knob {
                        return mouse::Interaction::ResizingVertically;
                    }
                    return mouse::Interaction::Pointer;
                }
            }
        }
        mouse::Interaction::default()
    }
}

#[cfg(test)]
pub fn key_rect(key: &Key) -> Rectangle {
    key_rect_with_size(key, Size::new(1484.0, BASE_BOARD_HEIGHT), false)
}

fn key_rect_with_size(key: &Key, size: Size, compact_crop: bool) -> Rectangle {
    let canonical = match key.cluster {
        Cluster::Alpha | Cluster::AlphaLight => {
            let row = key.row as usize;
            let source = key_geometry::alpha_key_source_rect(row, key.col, key.w);
            let (source_width, _) = key_geometry::ALPHA_SOURCE_SIZES[row - 1];
            let source_scale = ALPHA_W / source_width;
            Rectangle {
                x: ALPHA_X + source.x * source_scale,
                y: ALPHA_Y + (key.row - 1.0) * ALPHA_ROW_PITCH,
                width: source.width * source_scale,
                height: ALPHA_ROW_PITCH,
            }
        }
        Cluster::Nav => Rectangle {
            x: NAV_X + (key.col - 15.5) * (NAV_W / 3.0),
            y: NAV_Y + (key.row - 1.0) * (NAV_H / 2.0),
            width: key.w * (NAV_W / 3.0),
            height: key.h * (NAV_H / 2.0),
        },
        Cluster::Arrow => Rectangle {
            x: ARROW_X + (key.col - 15.5) * (ARROW_W / 3.0),
            y: ARROW_Y + (key.row - 4.0) * (ARROW_H / 2.0),
            width: key.w * (ARROW_W / 3.0),
            height: key.h * (ARROW_H / 2.0),
        },
        Cluster::Numpad => {
            let source = key_geometry::numpad_key_source_rect(
                (key.col - 19.0).round() as usize,
                key.row.round() as usize,
            );
            let x_scale = NUMPAD_W / key_geometry::NUMPAD_SOURCE_SIZE.0;
            let y_scale = NUMPAD_H / key_geometry::NUMPAD_SOURCE_SIZE.1;
            Rectangle {
                x: NUMPAD_X + source.x * x_scale,
                y: NUMPAD_Y + source.y * y_scale,
                width: source.width * x_scale,
                height: source.height * y_scale,
            }
        }
        Cluster::Encoder => {
            let index = key.knob_index.unwrap_or(12);
            if index == 12 {
                let opening: Rectangle = Rectangle {
                    x: 102.0,
                    y: 187.0,
                    width: 100.0,
                    height: 90.0,
                };
                let diameter = opening.width.min(opening.height) * 0.9;
                Rectangle {
                    x: opening.x + (opening.width - diameter) / 2.0,
                    y: opening.y + (opening.height - diameter) / 2.0,
                    width: diameter,
                    height: diameter,
                }
            } else {
                let group = (index / 4) as usize;
                let within = (index % 4) as f32;
                let banks: [(f32, f32, f32, f32); 3] = [
                    (260.0, 323.0, 190.0, 87.0),
                    (611.0, 309.0, 188.0, 91.0),
                    (947.0, 310.0, 188.0, 90.0),
                ];
                let (bank_x, bank_width, bank_y, bank_height) = banks[group];
                let segment = bank_width / 4.0;
                let diameter = bank_height.min(segment) * 0.9;
                Rectangle {
                    x: bank_x + (within + 0.5) * segment - diameter / 2.0,
                    y: bank_y + (bank_height - diameter) / 2.0,
                    width: diameter,
                    height: diameter,
                }
            }
        }
    };
    photo_rect(
        size,
        compact_crop,
        canonical.x,
        canonical.y,
        canonical.width,
        canonical.height,
    )
}

fn key_sprite_rect_with_size(
    key: &Key,
    size: Size,
    compact_crop: bool,
    blank_numpad: bool,
) -> Rectangle {
    let rect = key_rect_with_size(key, size, compact_crop);
    let source_aspect = match key.cluster {
        Cluster::Alpha | Cluster::AlphaLight => {
            let row = (key.row as usize).saturating_sub(1).min(4);
            let crop = key_geometry::alpha_key_source_rect(row + 1, key.col, key.w);
            crop.width / crop.height
        }
        Cluster::Nav => (467.0 / 3.0 * key.w) / (308.0 / 2.0 * key.h),
        Cluster::Arrow => (456.0 / 3.0 * key.w) / (322.0 / 2.0 * key.h),
        Cluster::Numpad => {
            let column = (key.col - 19.0).round() as usize;
            let row = key.row.round() as usize;
            let crop = if blank_numpad {
                key_geometry::clean_numpad_key_source_rect(column, row)
            } else {
                key_geometry::numpad_key_source_rect(column, row)
            };
            crop.width / crop.height
        }
        Cluster::Encoder => return rect,
    };
    Rectangle {
        height: rect.width / source_aspect,
        ..rect
    }
}

fn alpha_source_rect_with_size(
    row: usize,
    source: SourceRect,
    size: Size,
    compact_crop: bool,
) -> Rectangle {
    let (source_width, _) = key_geometry::ALPHA_SOURCE_SIZES[row - 1];
    let row_y = ALPHA_Y + (row as f32 - 1.0) * ALPHA_ROW_PITCH;
    let row_origin = photo_rect(size, compact_crop, ALPHA_X, row_y, 0.0, 0.0);
    let scale = photo_rect(size, compact_crop, ALPHA_X, row_y, ALPHA_W, 0.0).width / source_width;
    Rectangle {
        x: row_origin.x + source.x * scale,
        y: row_origin.y + source.y * scale,
        width: source.width * scale,
        height: source.height * scale,
    }
}

fn alpha_text_guide_with_size(
    key: &Key,
    size: Size,
    compact_crop: bool,
) -> Option<(Point, Option<Rectangle>)> {
    let row = key.row as usize;
    match key_geometry::alpha_text_guide(row, key.col)? {
        TextGuide::Center { x, y } => {
            let point = alpha_source_rect_with_size(
                row,
                SourceRect {
                    x,
                    y,
                    width: 0.0,
                    height: 0.0,
                },
                size,
                compact_crop,
            );
            Some((Point::new(point.x, point.y), None))
        }
        TextGuide::Bounds(bounds) => {
            let bounds = alpha_source_rect_with_size(row, bounds, size, compact_crop);
            Some((
                Point::new(
                    bounds.x + bounds.width / 2.0,
                    bounds.y + bounds.height / 2.0,
                ),
                Some(bounds),
            ))
        }
    }
}

fn numpad_source_rect_with_size(source: SourceRect, size: Size, compact_crop: bool) -> Rectangle {
    let origin = photo_rect(size, compact_crop, NUMPAD_X, NUMPAD_Y, 0.0, 0.0);
    let opening = photo_rect(size, compact_crop, NUMPAD_X, NUMPAD_Y, NUMPAD_W, NUMPAD_H);
    let x_scale = opening.width / key_geometry::NUMPAD_SOURCE_SIZE.0;
    let y_scale = opening.height / key_geometry::NUMPAD_SOURCE_SIZE.1;
    Rectangle {
        x: origin.x + source.x * x_scale,
        y: origin.y + source.y * y_scale,
        width: source.width * x_scale,
        height: source.height * y_scale,
    }
}

fn numpad_text_bounds_with_size(key: &Key, size: Size, compact_crop: bool) -> Option<Rectangle> {
    let TextGuide::Bounds(bounds) = key_geometry::numpad_text_guide(
        (key.col - 19.0).round() as usize,
        key.row.round() as usize,
    )?
    else {
        return None;
    };
    Some(numpad_source_rect_with_size(bounds, size, compact_crop))
}

fn fill_text_with_bounds(frame: &mut Frame, mut text: Text, bounds: Option<Rectangle>) {
    if let Some(bounds) = bounds {
        if bounds.width <= 0.0 || bounds.height <= 0.0 {
            return;
        }
        // Iced's WebGL canvas drops cached text placed in a nested clip draft.
        // Constrain the paragraph and conservatively fit a single-line label
        // instead: even a full-em-wide glyph cannot cross the marked box.
        let glyph_count = text.content.chars().count().max(1) as f32;
        let width_limit = bounds.width * 0.86 / glyph_count;
        let height_limit = bounds.height * 0.45;
        text.size = iced::Pixels(text.size.0.min(width_limit).min(height_limit).max(3.0));
        text.max_width = bounds.width;
    }
    frame.fill_text(text);
}

/// Returns (filter_color, text_color) for a key.
/// `lit_track`: Some(track) when playing, None when unlit.
fn key_colors(cluster: Cluster, lit_track: Option<usize>) -> (Color, Color) {
    let lit = lit_track.is_some();

    // For MIDI keys, use the track colour; fall back to gold for non-MIDI clusters.
    // usize::MAX - 1 = out-of-range warning (nearest key to a note off the board)
    if lit_track == Some(usize::MAX - 1) {
        let fill = rgb(0xFF, 0x3D, 0x72);
        return (fill, Color::WHITE);
    }

    let track_fill = |default_r, default_g, default_b| -> (Color, Color) {
        match lit_track {
            Some(t) if t != usize::MAX => {
                let (r, g, b) = TRACK_COLORS[t % TRACK_COLORS.len()];
                (Color::from_rgb8(r, g, b), Color::BLACK)
            }
            _ => (rgb(default_r, default_g, default_b), Color::BLACK),
        }
    };

    let (fill, text) = match (cluster, lit) {
        (Cluster::Alpha, false) => (rgb(0x66, 0x75, 0x5E), Color::WHITE),
        (Cluster::Alpha, true) => track_fill(0xFF, 0xA3, 0x55),
        (Cluster::AlphaLight, false) => (rgb(0xDF, 0xE3, 0xD2), Color::BLACK),
        (Cluster::AlphaLight, true) => track_fill(0xFF, 0xA3, 0x55),
        (Cluster::Nav, false) => (rgb(0xC9, 0xC6, 0xBA), Color::BLACK),
        (Cluster::Nav, true) => (rgb(0xFF, 0xB4, 0x58), Color::BLACK),
        (Cluster::Arrow, false) => (rgb(0xCF, 0x7F, 0x6C), Color::BLACK),
        (Cluster::Arrow, true) => (rgb(0xFF, 0x4C, 0x82), Color::WHITE),
        (Cluster::Numpad, false) => (rgb(0xD9, 0xD4, 0xC8), Color::BLACK),
        (Cluster::Numpad, true) => (rgb(0x50, 0xD4, 0xC8), Color::BLACK),
        (Cluster::Encoder, _) => (rgb(0x1D, 0x1B, 0x28), Color::WHITE),
    };

    (fill, text)
}

fn rgb(r: u8, g: u8, b: u8) -> Color {
    Color::from_rgb8(r, g, b)
}

