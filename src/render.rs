/// Embedded photographic pieces of the real K2. Keeping the handles alive in
/// `App` lets iced cache the decoded shell PNGs and generated key WebPs instead
/// of allocating them on every frame.
pub struct PhotoBoardAssets {
    pub shell: iced::widget::image::Handle,
    pub leds: iced::widget::image::Handle,
    /// Shared control-surface knob face (see
    /// `assets/keyboard/controls/README.md`) — the same physical-hardware
    /// asset family used for the mixer's CH/OCT knobs, reused here so the
    /// board's own 13 parameter knobs read as the same manufactured part.
    knob_face: iced::widget::image::Handle,
    key_sprites: RefCell<HashMap<(KeyId, u8, bool), iced::widget::image::Handle>>,
}

impl PhotoBoardAssets {
    pub fn new() -> Self {
        let handle = |bytes: &'static [u8]| iced::widget::image::Handle::from_bytes(bytes);
        Self {
            shell: handle(&include_bytes!("../assets/keyboard/keyboard-clean-mask.png")[..]),
            leds: handle(&include_bytes!("../assets/keyboard/led-panel-board-crop.png")[..]),
            // Downscaled once from the shared 1024px master, matching
            // `decode_and_downscale`'s use for the mixer knobs — these dials
            // render at well under 100px, and handing the GPU that much
            // minification directly risks the same mip-sampling artifacts
            // seen there.
            knob_face: crate::decode_and_downscale(
                &include_bytes!("../assets/keyboard/controls/rotary-knob-face.png")[..],
                128,
                128,
            ),
            key_sprites: RefCell::new(HashMap::new()),
        }
    }

    /// Selects an already-isolated, already-colourized WebP generated by
    /// `build.rs`. Runtime work is limited to creating and caching the image
    /// handle; no flood fill or per-pixel colour math can interrupt playback.
    fn key_sprite(
        &self,
        key: &Key,
        lit_track: Option<usize>,
        blank_numpad: bool,
    ) -> Option<iced::widget::image::Handle> {
        let variant = match lit_track {
            None => 0,
            Some(value) if value == usize::MAX - 1 => 10,
            Some(usize::MAX) => 9,
            Some(track) => 1 + (track % TRACK_COLORS.len()) as u8,
        };
        let blank_numpad = blank_numpad && matches!(key.cluster, Cluster::Numpad);
        if let Some(handle) = self
            .key_sprites
            .borrow()
            .get(&(key.id, variant, blank_numpad))
            .cloned()
        {
            return Some(handle);
        }
        let bytes = if blank_numpad {
            preprocessed_drum_key_sprite(key.id.0, variant)?
        } else {
            preprocessed_key_sprite(key.id.0, variant)?
        };
        let handle = iced::widget::image::Handle::from_bytes(bytes);
        self.key_sprites
            .borrow_mut()
            .insert((key.id, variant, blank_numpad), handle.clone());
        Some(handle)
    }
}

